/* Shared Workday chrome: header, global nav, Student flyout, footer, bottom bar.
   Call renderShell({active:'home'|'student', avatar:'JT'}) after icons.js. */
(function(){
  const STUDENT = {name:'Hudson Tinch', initials:'HT', id:'010204567'};
  window.DEMO_STUDENT = STUDENT;

  function header(){
    return `
    <header class="wd-header" role="banner">
      <a class="wd-logo" href="index.html" aria-label="University of Arkansas home"><img src="assets/ua-logo.png" alt="University of Arkansas"></a>
      <div class="wd-search" role="search">${icon('search')}<span>Search</span></div>
      <div class="wd-header-right">
        <button class="wd-iconbtn" aria-label="Notifications, 3 unread">${icon('notifications')}<span class="wd-badge">3</span></button>
        <button class="wd-iconbtn" aria-label="My Tasks">${icon('inbox')}</button>
        <button class="wd-avatar" aria-label="Profile">${STUDENT.initials}</button>
      </div>
    </header>`;
  }
  function nav(active){
    const item=(key,label,ic,href,isBtn)=>{
      const cls = key===active?'is-active':'';
      const inner=`<span class="ic">${icon(ic)}</span><span>${label}</span>`;
      return isBtn?`<button class="${cls}" data-fly="${key}" aria-haspopup="true">${inner}</button>`:`<a class="${cls}" href="${href}">${inner}</a>`;
    };
    return `
    <nav class="wd-nav" aria-label="Global">
      ${item('home','Home','home','index.html')}
      ${item('student','Student','book-open',null,true)}
      ${item('personal','Personal','user',null,true)}
      ${item('org','Organization','contact-card-cost-center',null,true)}
      ${item('ext','External Links','link',null,true)}
      <span class="spacer"></span>
      ${item('saved','Saved','media-mylearning','#')}
      <a href="#" aria-label="Settings" style="min-height:48px"><span class="ic">${icon('gear')}</span></a>
    </nav>
    <div class="wd-flyout" id="flyStudent" role="menu">
      <h3>Student</h3>
      <a href="academics.html" role="menuitem">Academics Hub</a>
      <a href="#" role="menuitem">Financials Hub</a>
      <a href="#" role="menuitem">Student Resources</a>
      <a href="#" role="menuitem">Academics</a>
      <a href="#" role="menuitem">Finances</a>
    </div>
    <nav class="wd-bottombar" aria-label="Global">
      <a href="index.html" class="${active==='home'?'is-active':''}"><span class="ic">${icon('home')}</span>Home</a>
      <a href="academics.html" class="${active==='student'?'is-active':''}"><span class="ic">${icon('book-open')}</span>Student</a>
      <a href="#"><span class="ic">${icon('user')}</span>Personal</a>
      <a href="#"><span class="ic">${icon('media-mylearning')}</span>Saved</a>
    </nav>`;
  }
  function footer(){
    return `
    <footer class="wd-footer">
      <svg class="wdlogo" width="104" height="34" viewBox="0 0 104 34" aria-label="Workday"><path d="M18 13 C 28 1, 44 1, 54 13" stroke="#f38b00" stroke-width="3.4" fill="none" stroke-linecap="round"/><text x="1" y="30" font-family="Roboto, Helvetica, Arial, sans-serif" font-weight="700" font-size="22" fill="#0f2f5c" letter-spacing="-0.6">workday.</text></svg>
      <p><a href="#">Privacy</a> © 2026 Workday, Inc. All rights reserved. This document was generated by Workday on behalf of the University of Arkansas System and its member institutions and organizations.</p>
      <p>System Status: Your system will be unavailable for a maximum of 3 hours during the next Weekly Service Update; starting on Friday, November 6, 2026 at 11:00 PM PST (GMT-8) until Saturday, November 7, 2026 at 2:00 AM PST (GMT-8).</p>
    </footer>`;
  }
  window.renderShell = function(opts){
    opts=opts||{};
    document.body.insertAdjacentHTML('afterbegin', header()+nav(opts.active||''));
    if(opts.footer!==false) document.body.insertAdjacentHTML('beforeend', footer());
    document.body.classList.add('has-bottombar');
    // flyout behaviour
    const fly=document.getElementById('flyStudent');
    document.querySelectorAll('[data-fly]').forEach(b=>{
      b.addEventListener('click',e=>{
        e.stopPropagation();
        if(b.dataset.fly==='student'){fly.classList.toggle('open');}
        else fly.classList.remove('open');
      });
    });
    document.addEventListener('click',e=>{ if(!fly.contains(e.target)) fly.classList.remove('open'); });
    document.addEventListener('keydown',e=>{ if(e.key==='Escape') fly.classList.remove('open'); });
  };
  window.toast = function(msg){
    let t=document.querySelector('.wd-toast');
    if(!t){t=document.createElement('div');t.className='wd-toast';document.body.appendChild(t);}
    t.innerHTML=icon('check-circle-fill')+'<span>'+msg+'</span>';
    requestAnimationFrame(()=>t.classList.add('show'));
    clearTimeout(t._h); t._h=setTimeout(()=>t.classList.remove('show'),3200);
  };
  window.todayLine = function(){
    const d=new Date(2026,10,3); // demo date: Tue Nov 3 2026
    return "It's "+d.toLocaleDateString('en-US',{weekday:'long',month:'long',day:'numeric',year:'numeric'});
  };
})();
